"""Metrics and the human-readable validation summary, computed from exported rows."""

from __future__ import annotations

from collections import Counter

from .bizhours import from_iso


def _pct(part: int, whole: int) -> float:
    return round(100 * part / whole, 2) if whole else 0.0


def _percentile(values: list[int], p: float) -> int:
    if not values:
        return 0
    values = sorted(values)
    return values[min(len(values) - 1, int(p * len(values)))]


def metrics(db: dict[str, list[dict]], detection: list[dict]) -> dict:
    tickets = {t["ticket_id"]: t for t in db["ticket"]}
    events = db["assignment_event"]
    n = len(tickets)

    # SLA attainment per channel x priority, resolution and first response.
    sla: dict[tuple[str, str], Counter] = {}
    for s in db["sla_event"]:
        tk = tickets[s["ticket_id"]]
        c = sla.setdefault((tk["channel_id"], tk["priority"]), Counter())
        c[s["event_type"]] += 1
    attainment = []
    for (ch, pr), c in sorted(sla.items()):
        met, br = c["RESOLUTION_MET"], c["RESOLUTION_BREACHED"]
        fr_met, fr_br = c["FIRST_RESPONSE_MET"], c["FIRST_RESPONSE_BREACHED"]
        attainment.append({"channel_id": ch, "priority": pr, "met": met, "breached": br, "pct": _pct(met, met + br),
                           "first_response_pct": _pct(fr_met, fr_met + fr_br)})

    assigns = [e for e in events if e["event_type"] == "ASSIGN"]
    kinds = Counter(e["event_type"] for e in events)
    translated = sum(e["translation_flag"] for e in assigns)

    # Wait = arrival to first assignment, in minutes.
    first_assign: dict[str, int] = {}
    for e in assigns:
        t = from_iso(e["ts"])
        first_assign[e["ticket_id"]] = min(t, first_assign.get(e["ticket_id"], t))
    waits = [first_assign[tid] - from_iso(tk["created_at"]) for tid, tk in tickets.items() if tid in first_assign]

    # Peak concurrent tickets per agent and channel (same slot rule as the validator).
    limits = {a["agent_id"]: {"EMAIL": a["max_concurrent_email"], "CHAT": a["max_concurrent_chat"],
                              "PHONE": a["max_concurrent_phone"]} for a in db["agent"]}
    by_tkt: dict[str, list[dict]] = {}
    for e in sorted(events, key=lambda e: (e["ticket_id"], e["seq"])):
        by_tkt.setdefault(e["ticket_id"], []).append(e)
    marks: dict[tuple[str, str], list[tuple[int, int]]] = {}
    for tid, evs in by_tkt.items():
        ch = tickets[tid]["channel_id"]
        for i, e in enumerate(evs):
            if e["event_type"] == "ASSIGN":
                end = from_iso(evs[i + 1]["ts"]) if i + 1 < len(evs) else 10**9
                marks.setdefault((e["agent_id"], ch), []).extend([(from_iso(e["ts"]), 1), (end, -1)])
    peak = []
    for (aid, ch), ms in sorted(marks.items()):
        load = top = 0
        for _, d in sorted(ms):          # -1 sorts before +1 at the same minute: release first
            load += d
            top = max(top, load)
        peak.append({"agent_id": aid, "channel_id": ch, "peak": top, "limit": limits[aid][ch]})

    return {
        "tickets": n, "messages": len(db["message"]), "agents": len(db["agent"]),
        "after_hours_pct": _pct(sum(t["after_hours"] for t in tickets.values()), n),
        "priority_mix": dict(sorted(Counter(t["priority"] for t in tickets.values()).items())),
        "channel_mix": dict(sorted(Counter(t["channel_id"] for t in tickets.values()).items())),
        "sla_attainment": attainment,
        "rates": {
            "transfer_rate": _pct(kinds["TRANSFER"], n), "escalation_rate": _pct(kinds["ESCALATE"], n),
            "reopen_rate": _pct(kinds["REOPEN"], n),
            "language_match_rate": _pct(len(assigns) - translated, len(assigns)),
            "translation_rate": _pct(translated, len(assigns)),
        },
        "queue_wait_minutes": {"p50": _percentile(waits, 0.5), "p90": _percentile(waits, 0.9),
                               "p99": _percentile(waits, 0.99), "max": max(waits, default=0)},
        "csat_distribution": {str(k): v for k, v in sorted(Counter(t["csat"] for t in tickets.values()
                                                                    if t["csat"] is not None).items())},
        "peak_concurrency": peak,
        "anomaly_detection": detection,
    }


def summary_markdown(info: dict, structural: list[dict], baseline_findings: int, findings: list[dict],
                     detection: list[dict], m: dict) -> str:
    """validation_summary.md: what was checked and what came out."""
    other = Counter(f["issue_type"] for f in findings
                    if f["issue_type"] not in {d["issue_type"] for d in detection})
    lines = [
        "# Validation summary", "",
        f"Scale `{info['scale']}`, seed `{info['seed']}`. Generated by `python -m caserouting generate "
        f"--scale {info['scale']} --seed {info['seed']}`.", "",
        "## Structural checks", "",
        "PK uniqueness, FK integrity, enums, ID formats, date ordering, natural-key duplicates, "
        "reconciliation of derived columns against events.", "",
        f"- Failures: **{len(structural)}**",
    ]
    lines += [f"  - `{f['check']}` {f['table']}: {f['detail']}" for f in structural[:20]]
    lines += [
        "", "## Business-rule checks", "",
        f"- Clean baseline (before injection): **{baseline_findings}** findings",
        f"- Findings outside the five labelled types after injection: **{sum(other.values())}** {dict(other) or ''}",
        "", "## Labelled anomalies vs. findings", "",
        "| issue_type | expected | found | missed | false positive |", "|---|---:|---:|---:|---:|",
    ]
    lines += [f"| {d['issue_type']} | {d['expected']} | {d['found']} | {d['missed']} | {d['false_positive']} |"
              for d in detection]
    over = [p for p in m["peak_concurrency"] if p["peak"] > p["limit"]]
    lines += [
        "", "## Acceptance criteria", "",
        "| Criterion | Evidence | Result |", "|---|---|---|",
        f"| Routing respects skill and capacity | eligibility + capacity sweep on every ASSIGN | "
        f"{'pass' if baseline_findings == 0 else 'FAIL'} on baseline; {len(over)} agent-channel peaks above limit "
        f"after injection (expected: only CAPACITY_EXCEEDED tickets) |",
        "| SLA is reproducible | due dates and outcomes recomputed from tickets + events | "
        f"{'pass' if baseline_findings == 0 else 'FAIL'} on baseline |",
        "| Escalation timing is correct | every ESCALATE at exactly 80% of the resolution target | "
        f"{'pass' if baseline_findings == 0 else 'FAIL'} on baseline |",
        "| Assignment history is complete | seq 1..n gapless, REOPEN after RESOLVE, legal lifecycle | "
        f"{'pass' if baseline_findings == 0 else 'FAIL'} on baseline |",
        "", "## Headline metrics", "",
        f"- Tickets {m['tickets']}, messages {m['messages']}, agents {m['agents']}, after-hours {m['after_hours_pct']}%",
        f"- Rates: {m['rates']}",
        f"- Queue wait minutes: {m['queue_wait_minutes']}",
        f"- CSAT distribution: {m['csat_distribution']}", "",
    ]
    return "\n".join(lines)
